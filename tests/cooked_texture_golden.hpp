// tests/cooked_mesh_golden.hpp shape, one format over.
//
// These are not "the bytes the code happens to produce today". Each was produced by a real cook, then
// verified FIELD BY FIELD against the container's own normative tables -- the 80-byte header and
// Index, the level-order inversion, the single padding site, the frozen Data Format Descriptor for its
// vkFormat, and the three-record key/value tiling -- before being frozen. A change to ANY layout rule,
// offset, ordering rule, padding rule, filter rule or encoder rule fails them by construction. If a
// golden has to change, THE COOK changed, and that is a COOKED_TEXTURE_COOKER_VERSION decision rather
// than a test edit.
//
// EACH GOLDEN CARRIES THE EXACT RGBA8 TEXELS IT WAS COOKED FROM, as a second literal array, so it is
// reproducible from this header alone: the cases that consume these arrays re-cook the input and
// compare, which is what makes the golden a statement about the whole transform rather than about a
// blob somebody once captured. The 5x3 one can be checked by hand against the polyphase filter's own
// arithmetic on fifteen texels.
//
// An in-source annotated array rather than a committed binary artifact, deliberately: it is reviewable
// in the diff, it needs no fixture path, it works in both reduced configurations, and one array serves
