// ---- Golden D: 2x2 Bc3Srgb, a NIL GUID, the full 2-level chain ---------------------------------
// THE ONLY GOLDEN THAT CARRIES THE CORRECTED ALPHA-QUALIFIER BYTE. BC3_SRGB's descriptor is NOT a
// one-byte edit of BC3_UNORM's: dfdutils' setChannelFlags sets KHR_DF_SAMPLE_DATATYPE_LINEAR (0x10)
// on an sRGB format's alpha sample, and KHR_DF_CHANNEL_BC3_ALPHA and KHR_DF_CHANNEL_RGBSDA_ALPHA are
// both 15, so the first sample's channel byte reads 1F rather than 0F. The KTX2 spec makes that a
// MUST, not a preference, so a file carrying 0F there is one an external validator rejects while
// every test in this tree stays green. In this array that byte is at FILE OFFSET 159 (descriptor
// offset 31, since the descriptor starts at 128), and it reads 0x1F.
//
// It also pins BC3's ALPHA-THEN-COLOUR composition in bytes, which until this golden existed was
// covered only behaviourally: level 0's first 8 bytes are the BC4 alpha block (r0 = 0xFF, r1 = 0x00 --
// max then min, over the four alphas 255/128/64/0) and its second 8 are the BC1 colour block.
//
//    0        identifier + header + Index                     = 80
//   80..127   two level records, LEVEL 0 FIRST                = 24 * 2
//  128..187   DFD for 138 BC3_SRGB                            = 60
//  188..307   KVD, three keys                                 = 120
//  308..319   mipPadding, align(308, 16) -> 320               = 12 zero bytes <- THE ONLY PAD SITE
//  320..335   level 1 (1x1), 1 block of 16
//  336..351   level 0 (2x2), 1 block of 16
//  total 352
//
