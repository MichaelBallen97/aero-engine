// The prefix every golden shares, restated once here rather than four times below:
//
//   0..11    the 12-byte Khronos identifier   AB 4B 54 58 20 32 30 BB 0D 0A 1A 0A
//   12..79   the nine-u32 header and the Index (dfd/kvd offsets and lengths, sgd = 0)
//   80..     the level index, 24 bytes per level, ORDERED LEVEL 0 FIRST
//   ...      the Data Format Descriptor for the declared vkFormat, 44 / 60 / 92 bytes
//   ...      the key/value data: AeroSourceGuid (52) + KTXorientation (24) + KTXwriter (44) = 120,
//            ALWAYS, for every file this cook writes
//   ...      mipPadding to lcm(bytesPerBlock, 4) -- THE ONLY PADDING SITE IN THE WHOLE FILE
//   ...      the level DATA, SMALLEST LEVEL FIRST, so levels[0].byteOffset is the largest offset
