//
// These are not "the bytes the code happens to produce today". Each was produced by a real cook,
// then verified FIELD BY FIELD against docs/09-file-formats.md section 12's own tables before being
// frozen -- header word by header word, record by record, including the parent remap, the palette
// slots, every TRS component, every inverse-bind cell and both reserved regions. A change to ANY
// layout rule, offset, ordering rule or padding rule fails them by construction. If a golden has to
// change, the FORMAT changed -- and that is a formatVersion decision, not a test edit.
//
// An in-source annotated array rather than a committed binary artifact, deliberately: it is
// reviewable in the diff, it needs no fixture path, it works in both reduced configurations, and one
// array serves two test binaries.
