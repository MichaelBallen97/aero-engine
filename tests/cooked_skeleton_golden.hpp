// ---- Golden B: the CLOSURE skeleton, which pins what Golden A cannot ----------------------------
// Input (tests/skeleton_cook_test.cpp's closureJoints()): a REAL sourceGuid
// {0x0123456789ABCDEF, 0xFEDCBA9876543210} -- so both header u64 halves are byte-visible --
// sourceSkinIndex 0, and three joints:
//
//   Root  localId 10, no parent, paletteSlot INVALID (HIERARCHY-ONLY), T (0,1,0),
//         input IBM = translate(9,9,9) -- deliberately absurd, and it MUST NOT appear below
//   left  localId 20, parent 10, paletteSlot 1, T (1,0,0),  IBM = translate(-1,-1,0)
//   right localId 30, parent 10, paletteSlot 0, T (-1,0,0), IBM = translate(1,-1,0)
//
// Three properties live in these bytes and in no other artifact of this task:
//   * the hierarchy-only record's IBM is written as IDENTITY (offsets 120/140/160/180 hold 1.0f and
