// tests/cooked_animation_golden.hpp -- task 3.5.2: THE TWO FROZEN BYTE GOLDENS of the .aeroanim
// container v1. Included by tests/cooked_animation_test.cpp and tests/animation_cook_test.cpp (same
// directory), and reachable from tests/editor/ through aero_editor_shell_test's existing
