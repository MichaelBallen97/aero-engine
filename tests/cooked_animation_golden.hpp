// ---- Golden B: the MIXED clip, which pins what Golden A cannot -----------------------------------
// Input (tests/animation_cook_test.cpp's mixedChannels()): a REAL sourceGuid
// {0x0123456789ABCDEF, 0xFEDCBA9876543210} -- so both header u64 halves are byte-visible --
// sourceAnimationIndex 2, and three channels, one per interpolation mode, supplied in THIS order:
//
//   slot 0  node 7, Scale,       CubicSpline, 2 keys / 6 values (inTangent, value, outTangent)
//   slot 1  node 3, Rotation,    Linear,      3 keys / 3 values
//   slot 2  node 7, Translation, Step,        2 keys / 2 values, w = 7 and w = -8 ON INPUT
//
// Four properties live in these bytes and in no other artifact of this task:
//   * the emitted order is (3, Rotation), (7, Translation), (7, Scale) -- ascending by
//     (targetNodeLocalId, path), i.e. input slots 1, 2, 0. TWO of the three channels are on the SAME
//     node, which is what makes this array the only artifact of this task that can SEE the path half
//     of the sort key disappear: drop it and those two collide on one key, so the order stops being
//     (Translation, Scale) AND the cook's duplicate sweep -- the thing that makes the order total --
//     refuses the clip outright. With three DISTINCT nodes neither consequence exists and the same
//     defect reddens nothing at all. THE COMPOSITION IS PART OF THE FIXTURE'S CONTRACT.
//     Measured: seeding exactly that reddens six cases here, KA2 and KA3 among them.
//   * the array is simultaneously the ORDER-INDEPENDENCE proof: animation_cook_test.cpp's KA3 cooks
//     all six permutations of these three channels and requires these exact bytes from each.
//   * the Translation values' caller-supplied w is GONE -- offsets 268 and 284 hold 0x00000000, and
//     7.0f (0x40E00000) and -8.0f (0xC1000000) appear nowhere in the file.
//   * the total key count is 7, so keyCount mod 4 is 3 and the single padding site is present and
