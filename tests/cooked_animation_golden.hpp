// frozen -- header word by header word, record by record, both regions, the padding site and every
// reserved field. A change to ANY layout rule, offset, ordering rule or padding rule fails them by
// construction. If a golden has to change, the FORMAT changed -- and that is a formatVersion
// decision, not a test edit.
//
// An in-source annotated array rather than a committed binary artifact, deliberately: it is
// reviewable in the diff, it needs no fixture path, it works in both reduced configurations, and one
// array serves two test binaries.
