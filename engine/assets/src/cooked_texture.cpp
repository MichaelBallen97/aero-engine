// ---- the eight frozen Data Format Descriptors ----------------------------------------------------
//
// DERIVED FROM dfdutils' OWN createdfd.c (createDFDCompressed / createDFDUnpacked / writeHeader /
// writeSample) AND khr_df.h, NOT BY HAND -- and then regenerated by compiling that file and dumping
// its output byte for byte, because our own parser compares the DFD against the same table our
// writer emits, so every test in this tree passes with a wrong table and only an external validator
// can tell. Layout of each: 4 bytes of dfdTotalSize, then six basic-block words, then 16 bytes per
// sample.
//   word 0  vendorId(0) | descriptorType(0) << 17
//   word 1  versionNumber(2) | descriptorBlockSize << 16   -- 2 is KHR_DF_VERSIONNUMBER_1_4, which
//                                                             khr_df.h notes did not bump the block
//                                                             version number from 1.3
//   word 2  colorModel | primaries(1, BT709) << 8 | transferFunction << 16 | flags(0, straight) << 24
//   word 3  (blockW-1) | (blockH-1) << 8 | (blockD-1) << 16 | (blockE-1) << 24   -- all zero unpacked
//   word 4  bytesPlane0 (the block byte size) in the low byte, planes 1..3 above it
//   word 5  bytesPlane4..7, all zero
//   sample  bitOffset | (bitLength-1) << 16 | channelId << 24 ; samplePosition ; lower ; upper
//
// THE ALPHA QUALIFIER, AND WHY THE sRGB TABLES ARE NOT ONE-BYTE EDITS OF THEIR UNORM SIBLINGS.
// setChannelFlags(channel, s_SRGB) sets KHR_DF_SAMPLE_DATATYPE_LINEAR (0x10) when the channel id
// equals KHR_DF_CHANNEL_RGBSDA_ALPHA (15), and both KHR_DF_CHANNEL_BC3_ALPHA and the alpha channel
// writeSample maps a channel-3 request to are ALSO 15 -- so BC3_SRGB's first sample and
// R8G8B8A8_SRGB's fourth carry channel byte 1F, not 0F. The KTX2 spec makes this a MUST, not a
// preference: "If transferFunction is not KHR_DF_TRANSFER_LINEAR or KHR_DF_TRANSFER_UNSPECIFIED and
// an alpha channel exists, KHR_DF_SAMPLE_DATATYPE_LINEAR must be set in the qualifiers field of the
// alpha sample." BC1_RGB_SRGB is genuinely a one-byte edit, because its only sample is channel 0.
// Do not "simplify" the three sRGB tables into byte patches of their siblings -- one of them is, two
// of them are not, and the two that are not are the ones an external validator rejects.
//
// THEY ARE EXPLICIT BYTE LITERALS AND NEVER SHIFT-AND-OR EXPRESSIONS, for two reasons. A table that
// is COMPUTED can be computed wrongly in a way its own reader agrees with, which is the circularity
// above. And `(uint32_t)channel << 24` with channel 128..132 shifts into a sign bit if the value is
// ever handled as a signed type -- createdfd.c carries its own comment about that. A literal cannot.

// 131 VK_FORMAT_BC1_RGB_UNORM_BLOCK -- 44 bytes, one sample.
constexpr std::array<std::uint8_t, KTX2_DFD_BYTES_1_SAMPLE> DFD_BC1_RGB_UNORM = {
    0x2C, 0x00, 0x00, 0x00,  // dfdTotalSize 44
    0x00, 0x00, 0x00, 0x00,  // word 0  vendorId 0 | descriptorType 0
    0x02, 0x00, 0x28, 0x00,  // word 1  versionNumber 2 | descriptorBlockSize 40
    0x80, 0x01, 0x01, 0x00,  // word 2  model 128 BC1A | primaries 1 | transfer 1 LINEAR | flags 0
    0x03, 0x03, 0x00, 0x00,  // word 3  texel block 4x4x1x1, each extent stored minus one
    0x08, 0x00, 0x00, 0x00,  // word 4  bytesPlane0 8
    0x00, 0x00, 0x00, 0x00,  // word 5  bytesPlane4..7 0
    0x00, 0x00, 0x3F, 0x00,  // sample 0  bitOffset 0 | bitLength 64 | channel 0 BC1A_COLOR
    0x00, 0x00, 0x00, 0x00,  //           samplePosition 0
    0x00, 0x00, 0x00, 0x00,  //           sampleLower 0
    0xFF, 0xFF, 0xFF, 0xFF,  //           sampleUpper 0xFFFFFFFF
};

