std::string_view toString(CookedTextureFormat format) noexcept {
    switch (format) {
        case CookedTextureFormat::Rgba8Unorm:
            return "Rgba8Unorm";
        case CookedTextureFormat::Rgba8Srgb:
            return "Rgba8Srgb";
        case CookedTextureFormat::Bc1RgbUnorm:
            return "Bc1RgbUnorm";
        case CookedTextureFormat::Bc1RgbSrgb:
            return "Bc1RgbSrgb";
        case CookedTextureFormat::Bc3Unorm:
            return "Bc3Unorm";
        case CookedTextureFormat::Bc3Srgb:
            return "Bc3Srgb";
        case CookedTextureFormat::Bc4Unorm:
            return "Bc4Unorm";
        case CookedTextureFormat::Bc5Unorm:
            return "Bc5Unorm";
    }
    return "Unknown";  // unreachable; the switch has no default so a new enumerator is a -Wswitch error
}

std::span<const std::uint8_t> cookedTextureDescriptorBytes(CookedTextureFormat format) noexcept {
    switch (format) {
        case CookedTextureFormat::Rgba8Unorm:
            return DFD_RGBA8_UNORM;
        case CookedTextureFormat::Rgba8Srgb:
            return DFD_RGBA8_SRGB;
        case CookedTextureFormat::Bc1RgbUnorm:
            return DFD_BC1_RGB_UNORM;
        case CookedTextureFormat::Bc1RgbSrgb:
            return DFD_BC1_RGB_SRGB;
        case CookedTextureFormat::Bc3Unorm:
            return DFD_BC3_UNORM;
        case CookedTextureFormat::Bc3Srgb:
            return DFD_BC3_SRGB;
        case CookedTextureFormat::Bc4Unorm:
            return DFD_BC4_UNORM;
        case CookedTextureFormat::Bc5Unorm:
            return DFD_BC5_UNORM;
    }
    return {};  // unreachable; the switch has no default so a new enumerator is a -Wswitch error
}

std::string_view cookedTextureStatusLabel(CookedTextureStatus status) noexcept {
    switch (status) {
        case CookedTextureStatus::Ok:
            return "Ok";
        case CookedTextureStatus::TooSmall:
            return "Too small";
        case CookedTextureStatus::BadIdentifier:
            return "Bad identifier";
        case CookedTextureStatus::UnsupportedFormat:
            return "Unsupported format";
        case CookedTextureStatus::UnsupportedShape:
            return "Unsupported shape";
        case CookedTextureStatus::Supercompressed:
            return "Supercompressed";
        case CookedTextureStatus::CapExceeded:
            return "Cap exceeded";
        case CookedTextureStatus::BadTable:
            return "Bad table";
        case CookedTextureStatus::BadRange:
            return "Bad range";
        case CookedTextureStatus::BadDescriptor:
            return "Bad descriptor";
    }
    return "Unknown";  // unreachable; the switch has no default so a new enumerator is a -Wswitch error
}

